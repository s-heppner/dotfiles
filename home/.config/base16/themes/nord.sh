BASE04="d8dee9"  # Dark foreground (status bars)
BASE05="e5e9f0"  # Default foreground
BASE06="eceff4"  # Light foreground
BASE07="8fbcbb"  # Light background
BASE08="bf616a"  # Red   — variables, errors, diff deleted
BASE09="d08770"  # Orange — integers, constants
BASE0A="ebcb8b"  # Yellow — classes, search highlight
BASE0B="a3be8c"  # Green  — strings, diff inserted
BASE0C="88c0d0"  # Cyan   — support, escapes, regex
BASE0D="81a1c1"  # Blue   — functions, methods
BASE0E="b48ead"  # Purple — keywords
BASE0F="5e81ac"  # Brown  — deprecated, embedded punctuation
