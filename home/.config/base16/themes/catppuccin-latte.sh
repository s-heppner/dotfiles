# base16 catppuccin-latte
# Author: https://github.com/catppuccin/catppuccin
# base16 palette. Data only: this file is sourced by the theme loader in
# `.bashrc_scripts/colors.sh` and by `base16-tmux`. It must not have side
# effects — only declare BASE00..BASE0F as 6-digit RGB hex (no leading '#').
#
# Note: a *light* palette — the background slots (base00..base07) run light to
# dark, the reverse of the dark themes.
BASE00="eff1f5"  # Default background
BASE01="e6e9ef"  # Lighter background (status bars, line highlight)
BASE02="ccd0da"  # Selection background
BASE03="bcc0cc"  # Comments, invisibles, line highlight
BASE04="acb0be"  # Dark foreground (status bars)
BASE05="4c4f69"  # Default foreground
BASE06="dc8a78"  # Light foreground
BASE07="7287fd"  # Light background
BASE08="d20f39"  # Red   — variables, errors, diff deleted
BASE09="fe640b"  # Orange — integers, constants
BASE0A="df8e1d"  # Yellow — classes, search highlight
BASE0B="40a02b"  # Green  — strings, diff inserted
BASE0C="179299"  # Cyan   — support, escapes, regex
BASE0D="1e66f5"  # Blue   — functions, methods
BASE0E="8839ef"  # Purple — keywords
BASE0F="dd7878"  # Brown  — deprecated, embedded punctuation
